"""Builds docs/changelog.toml, the launcher's "What's new" page, from the
repository's merged pull requests: each one's number, merge date, title and
a one-line summary taken from its description. Public text only (what the
pull requests already say on GitHub), with the attribution lines, headings,
check-run details and anything that looks like a local path left out.

    python -I tools/changelog/changelog.py [--repo owner/name] [--limit 200] [--out docs/changelog.toml]
    python -I tools/changelog/changelog.py --input prs.json      # from a saved `gh pr list` answer

The list comes from `gh pr list --state merged --json number,title,body,mergedAt`.
Standard library only; nothing is sent anywhere.
"""

from __future__ import annotations

import argparse
import datetime as _dt
import json
import os
import re
import subprocess
import sys
from pathlib import Path

REPO = "bstoney-yt/Mercenaries-2-Decompilation"
SUMMARY_MAX = 160

# Paragraphs that are not the change itself.
SKIP_START = (
    "<!--", "_requested by", "requested by", "#", "stacked on", "based on", "🤖", "co-authored-by",
    "pass condition", "|", "```", ">", "closes", "fixes #", "(cherry-picked", "cherry-picked",
)
# Anything that looks like a path on a machine, an address or a mention.
PRIVATE = re.compile(r"[A-Za-z]:\\|\\\\|/Users/|/home/|@[A-Za-z0-9-]+|https?://|\b\d{1,3}(\.\d{1,3}){3}\b")


def plain(text: str) -> str:
    """Markdown to plain text, on one line."""
    t = re.sub(r"`([^`]*)`", r"\1", text)
    t = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", t)
    t = re.sub(r"[*_]{1,3}([^*_]+)[*_]{1,3}", r"\1", t)
    return re.sub(r"\s+", " ", t).strip()


def summary(body: str | None, private: tuple[str, ...] = ()) -> str:
    """The first sentence of the first paragraph that says what changed,
    or "" when none is fit to show. A sentence naming any of `private`
    (people's names, given at run time) is skipped, as is one that only
    leads into a list (ends in a colon)."""
    if not body:
        return ""
    for para in re.split(r"\n\s*\n", body.replace("\r\n", "\n")):
        p = para.strip()
        low = p.lower()
        if not p or low.startswith(SKIP_START) or p.startswith(("- ", "* ", "1.")):
            continue
        text = plain(p)
        if not text or PRIVATE.search(text):
            continue
        m = re.match(r"(.+?[.!?])(\s|$)", text)
        sentence = m.group(1) if m else text
        if sentence.endswith(":") or any(w.lower() in sentence.lower() for w in private if w):
            continue
        if len(sentence) > SUMMARY_MAX:
            sentence = sentence[: SUMMARY_MAX - 3].rsplit(" ", 1)[0] + "..."
        return sentence
    return ""


def title(t: str) -> str:
    t = plain(t)
    return "" if PRIVATE.search(t) else t


def entries(prs: list[dict], private: tuple[str, ...] = ()) -> list[dict]:
    """Newest first: number, date (UTC), title, summary."""
    out = []
    for pr in prs:
        when = pr.get("mergedAt")
        t = title(pr.get("title", ""))
        if any(w.lower() in t.lower() for w in private if w):
            continue
        if not when or not t:
            continue
        date = _dt.datetime.fromisoformat(when).astimezone(_dt.UTC).date()
        out.append({"pr": int(pr["number"]), "date": date.isoformat(), "title": t, "summary": summary(pr.get("body"), private)})
    out.sort(key=lambda e: (e["date"], e["pr"]), reverse=True)
    return out


def q(s: str) -> str:
    """A TOML basic string."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def to_toml(es: list[dict], generated: str) -> str:
    lines = [
        "# The launcher's \"What's new\": merged pull requests, newest first.",
        "# Generated by tools/changelog/changelog.py from the pull requests' public titles",
        "# and descriptions; edit by hand only to drop or reword an entry.",
        "",
        f"generated = {q(generated)}",
    ]
    for e in es:
        lines += ["", "[[entry]]", f"pr = {e['pr']}", f"date = {q(e['date'])}", f"title = {q(e['title'])}"]
        if e["summary"]:
            lines.append(f"summary = {q(e['summary'])}")
    return "\n".join(lines) + "\n"


def fetch(repo: str, limit: int) -> list[dict]:
    p = subprocess.run(
        ["gh", "pr", "list", "--repo", repo, "--state", "merged", "--limit", str(limit),
         "--json", "number,title,body,mergedAt"],
        capture_output=True, text=True, encoding="utf-8", check=False)
    if p.returncode != 0:
        sys.exit(f"gh pr list failed: {p.stderr.strip()}")
    return json.loads(p.stdout)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo", default=REPO)
    ap.add_argument("--limit", type=int, default=200)
    ap.add_argument("--input", help="a saved gh pr list JSON answer instead of asking GitHub")
    ap.add_argument("--out", default="docs/changelog.toml")
    ap.add_argument("--private", default=os.environ.get("CHANGELOG_PRIVATE", ""),
                    help="comma-separated words (people's names) no summary may contain; "
                         "default $CHANGELOG_PRIVATE")
    a = ap.parse_args(argv)
    prs = json.loads(Path(a.input).read_text(encoding="utf-8")) if a.input else fetch(a.repo, a.limit)
    es = entries(prs, tuple(w.strip() for w in a.private.split(",") if w.strip()))
    today = _dt.datetime.now(_dt.UTC).date().isoformat()
    Path(a.out).write_text(to_toml(es, today), encoding="utf-8")
    print(f"{len(es)} entries -> {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
